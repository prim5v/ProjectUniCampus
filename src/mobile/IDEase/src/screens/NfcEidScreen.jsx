// Your Lottie file
const NFC_ANIMATION = require("../../assets/animations/6.json");

export default function NfcEidScreen() {
    const [mode, setMode] = useState("nfc");

    // QR generated by the native Android module
    const [qrValue, setQrValue] = useState(null);
    const [qrLoading, setQrLoading] = useState(false);

    // const { UniCampusHCE } = NativeModules;
    // const UnicampusHCE = UniCampusHCE;

    /**
     * Generate a fresh QR using the native Android module.
     */
    const generateQr = async () => {
        try {
            // Make sure the native module exists
            if (!UnicampusHCE) {
                throw new Error(
                    "UnicampusHCE native module is not available"
                );
            }

            if (!UnicampusHCE.generateQr) {
                throw new Error(
                    "generateQr() is not available on UnicampusHCE"
                );
            }

            setQrLoading(true);

            console.log("🔐 Generating secure QR...");

            const qr = await UnicampusHCE.generateQr();

            console.log("🔐 GENERATED QR:", qr);

            if (!qr) {
                throw new Error("Native QR generator returned an empty value");
            }

            setQrValue(qr);
        } catch (error) {
            console.error("❌ QR GENERATION ERROR:", error);

            setQrValue(null);
        } finally {
            setQrLoading(false);
        }
    };

    /**
     * Switch to NFC mode.
     */
    const handleNfcMode = () => {
        setMode("nfc");
    };

    /**
     * Switch to QR mode and generate
     * a fresh QR immediately.
     */
    const handleQrMode = async () => {
        setMode("qr");
        await generateQr();
    };

    return (
        <SafeAreaView style={styles.container}>
            {/* HEADER */}
            <ScreenHeader
                title="NFC e-ID"
                onBackPress={() => router.back()}
                showBackButton={true}
            />

            {/* MAIN CONTENT */}
            <View style={styles.content}>
                {mode === "nfc" ? (
                    <NfcView />
                ) : (
                    <QrView
                        value={qrValue}
                        loading={qrLoading}
                        onRegenerate={generateQr}
                    />
                )}
            </View>

            {/* MODE SWITCHER */}
            <View style={styles.modeContainer}>
                {/* NFC BUTTON */}
                <TouchableOpacity
                    style={[
                        styles.modeButton,
                        mode === "nfc" && styles.activeMode,
                    ]}
                    activeOpacity={0.8}
                    onPress={handleNfcMode}
                >
                    <Text
                        style={[
                            styles.modeText,
                            mode === "nfc" && styles.activeModeText,
                        ]}
                    >
                        NFC
                    </Text>
                </TouchableOpacity>

                {/* QR BUTTON */}
                <TouchableOpacity
                    style={[
                        styles.modeButton,
                        mode === "qr" && styles.activeMode,
                    ]}
                    activeOpacity={0.8}
                    onPress={handleQrMode}
                >
                    <Text
                        style={[
                            styles.modeText,
                            mode === "qr" && styles.activeModeText,
                        ]}
                    >
                        QR
                    </Text>
                </TouchableOpacity>
            </View>
        </SafeAreaView>
    );
}

