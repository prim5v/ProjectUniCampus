function QrView({ value, loading, onRegenerate }) {
    const [timeLeft, setTimeLeft] = useState(1 * 60);

    /**
     * Countdown timer.
     *
     * The QR is valid for 5 minutes.
     */
    useEffect(() => {
        if (timeLeft <= 0) {
            return;
        }

        const interval = setInterval(() => {
            setTimeLeft((prev) => {
                if (prev <= 1) {
                    clearInterval(interval);
                    return 0;
                }

                return prev - 1;
            });
        }, 1000);

        return () => clearInterval(interval);
    }, [timeLeft]);

    /**
     * When the QR expires, generate a new one.
     */
    useEffect(() => {
        if (timeLeft === 0 && !loading) {
            console.log("⏰ QR expired");

            onRegenerate();

            // Reset countdown
            setTimeLeft(1 * 60);
        }
    }, [timeLeft, loading]);

    const minutes = Math.floor(timeLeft / 60)
        .toString()
        .padStart(2, "0");

    const seconds = (timeLeft % 60)
        .toString()
        .padStart(2, "0");

    return (
        <View style={styles.qrView}>
            {/* TITLE */}
            <Text style={styles.qrTitle}>
                Scan to verify
            </Text>

            {/* DESCRIPTION */}
            <Text style={styles.qrSubtitle}>
                Present this code to a UniCampus reader
            </Text>

            {/* EXPIRY */}
            <Text style={styles.qrExpiry}>
                Expires in{" "}
                <Text style={styles.timer}>
                    {minutes}:{seconds}
                </Text>
            </Text>

            {/* QR CONTAINER */}
            <View style={styles.qrContainer}>
                {loading ? (
                    <View style={styles.qrPlaceholder}>
                        <Text style={styles.qrLoading}>
                            Generating secure QR...
                        </Text>
                    </View>
                ) : value ? (
                    <QRCode
                        value={value}
                        size={width * 0.62}
                        color="#000000"
                        backgroundColor="#FFFFFF"
                        quietZone={18}
                    />
                ) : (
                    <View style={styles.qrPlaceholder}>
                        <Text style={styles.qrLoading}>
                            Unable to generate QR
                        </Text>

                        <TouchableOpacity
                            style={styles.retryButton}
                            activeOpacity={0.8}
                            onPress={onRegenerate}
                        >
                            <Text style={styles.retryText}>
                                Try again
                            </Text>
                        </TouchableOpacity>
                    </View>
                )}
            </View>

            {/* HINT */}
            <Text style={styles.qrHint}>
                Keep your screen steady while scanning
            </Text>
        </View>
    );
}

