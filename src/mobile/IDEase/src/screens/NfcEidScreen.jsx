function NfcView() {

    const [hceAvailable, setHceAvailable] = useState(null);
    const [nfcEnabled, setNfcEnabled] = useState(null);
    const [checking, setChecking] = useState(true);

    useEffect(() => {
        checkNfcStatus();
    }, []);

    const checkNfcStatus = async () => {

        try {

            setChecking(true);

            console.log("🔍 Checking HCE support...");

            const hasHce = await UniCampusHCE.hasHce();

            console.log("📱 HCE available:", hasHce);

            setHceAvailable(hasHce);

            // If device doesn't support HCE,
            // there is no need to check NFC state.
            if (!hasHce) {
                setNfcEnabled(false);
                return;
            }

            console.log("🔍 Checking NFC status...");

            const enabled = await UniCampusHCE.isNfcEnabled();

            console.log("📡 NFC enabled:", enabled);

            setNfcEnabled(enabled);

        } catch (error) {

            console.error(
                "❌ NFC STATUS CHECK ERROR:",
                error
            );

            // Fail safely into QR fallback
            setHceAvailable(false);
            setNfcEnabled(false);

        } finally {

            setChecking(false);

        }
    };


    // --------------------------------
    // CHECKING
    // --------------------------------

    if (checking) {

        return (
            <View style={styles.nfcView}>

                <View style={styles.animationContainer}>

                    <LottieView
                        source={NFC_ANIMATION}
                        autoPlay
                        loop
                        style={styles.nfcAnimation}
                    />

                </View>

                <View style={styles.statusContainer}>

                    <Text style={styles.statusTitle}>
                        Checking NFC
                    </Text>

                    <Text style={styles.statusSubtitle}>
                        Checking device capabilities...
                    </Text>

                </View>

            </View>
        );
    }


    // --------------------------------
    // NO HCE
    // --------------------------------

    if (hceAvailable === false) {

        return (
            <View style={styles.nfcView}>

                <View style={styles.animationContainer}>

                    {/* You can replace this with
                        your QR fallback image/Lottie */}
                    <Text style={styles.fallbackIcon}>
                        QR
                    </Text>

                </View>

                <View style={styles.statusContainer}>

                    <Text style={styles.statusTitle}>
                        NFC ID unavailable
                    </Text>

                    <Text style={styles.statusSubtitle}>
                        This device does not support Host Card Emulation.
                        Use the QR fallback to access your digital ID.
                    </Text>

                </View>

            </View>
        );
    }


    // --------------------------------
    // HCE EXISTS BUT NFC IS OFF
    // --------------------------------

    if (hceAvailable === true && nfcEnabled === false) {

        return (
            <View style={styles.nfcView}>

                <View style={styles.animationContainer}>

                    {/* Replace this with your
                        enable-NFC Lottie/image */}
                    <Text style={styles.nfcOffIcon}>
                        NFC
                    </Text>

                </View>

                <View style={styles.statusContainer}>

                    <Text style={styles.statusTitle}>
                        Enable NFC
                    </Text>

                    <Text style={styles.statusSubtitle}>
                        NFC is currently disabled. Turn on NFC in your
                        device settings to use your digital ID.
                    </Text>

                </View>

            </View>
        );
    }


    // --------------------------------
    // HCE + NFC ENABLED
    // --------------------------------

    return (

        <View style={styles.nfcView}>

            <View style={styles.animationContainer}>

                <LottieView
                    source={NFC_ANIMATION}
                    autoPlay
                    loop
                    style={styles.nfcAnimation}
                />

            </View>

            <View style={styles.statusContainer}>

                <Text style={styles.statusTitle}>
                    Working in background
                </Text>

                <Text style={styles.statusSubtitle}>
                    No internet required
                </Text>

            </View>

        </View>
    );
}

